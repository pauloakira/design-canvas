// Bundles the Figma plugin's main thread (figma-plugin/code.js) from its sources.
// No bundler needed: the engine is a plain script that defines dcCreateApplier().
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'figma-plugin');
const engine = fs.readFileSync(path.join(dir, 'src', 'engine.js'), 'utf8');
const main = fs.readFileSync(path.join(dir, 'src', 'main.js'), 'utf8');
const out = `// GENERATED by scripts/build-figma-plugin.mjs from figma-plugin/src — do not edit.\n${engine}\n${main}`;
fs.writeFileSync(path.join(dir, 'code.js'), out);
console.log(`figma-plugin/code.js (${(out.length / 1024).toFixed(1)} KB)`);
